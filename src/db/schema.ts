/**
 * Drizzle schema mirror of the Flyway-owned Postgres schema.
 *
 * **Flyway owns the schema.** This file is a hand-written mirror of the
 * final shape produced by running `db/migration/V1__create_mission_table.sql`
 * through `V18__drop_mission_restored_audit_action.sql`, in order, against a
 * fresh database — it is never executed as a migration itself, and Drizzle
 * never runs `migrate`/`push` against a real database in this project.
 *
 * Canonical regeneration path (once a DB is migrated and reachable):
 *
 *   pnpm db:pull   (i.e. drizzle-kit pull --config=drizzle.config.ts)
 *
 * `drizzle-kit pull` introspects the live, Flyway-migrated database and
 * regenerates this file (and a snapshot) from the real catalog — that
 * output supersedes this hand-mirror the moment a database exists. Until
 * then, every table/column/constraint below was transcribed by reading all
 * 18 migration files, not by running `pull` (no DB is configured in this
 * environment yet). `pull`-regenerated output drops this header comment and
 * the `$type<...>()` string-literal-union narrowing below — both need to be
 * re-applied by hand after a real `pull`.
 *
 * CI drift guard: `pnpm db:check`, i.e. `node scripts/check-schema-drift.mjs`
 * — NOT bare `drizzle-kit check` (that command only validates a migration-
 * snapshot *history* against itself, never against a live database, and
 * this project never runs `drizzle-kit generate`/`migrate` for real, so that
 * history never exists here). The script instead runs `drizzle-kit generate`
 * against this file and `drizzle-kit introspect` against the live
 * DATABASE_URL, each into a throwaway temp dir, and deep-compares their
 * normalized snapshot JSON — immune to the comment/`$type<...>()` noise a
 * raw file diff would produce. See that script's header for the full
 * mechanism; wired into `.github/workflows/ci.yml` once DATABASE_URL is
 * available as a secret.
 *
 * This module intentionally has no `import "server-only"`: drizzle-kit's
 * `generate`/`introspect`/`push` CLIs load this file directly via `require`,
 * outside the `react-server` condition, and `server-only`'s guard throws
 * unconditionally in that context — it has no secrets or IO of its own to
 * guard against being bundled into a client component.
 *
 * Conventions ported from the migrations:
 * - Every PK is `BIGINT GENERATED BY DEFAULT AS IDENTITY` → `.generatedByDefaultAsIdentity()`.
 * - Every `TIMESTAMP(6) WITH TIME ZONE` → `timestamp(..., { precision: 6, withTimezone: true })`.
 * - Enum-shaped columns are plain `VARCHAR` + a `CHECK (col IN (...))` constraint in
 *   Postgres (no native `CREATE TYPE ... AS ENUM` was ever used) — mirrored here as a
 *   `varchar` column whose TS type is narrowed to a string-literal union via `.$type<...>()`,
 *   plus the matching `check()` builder so the constraint itself round-trips too.
 *
 * Source (read in full, V1 → V18):
 * drone-missions-backend/drone-missions/src/main/resources/db/migration/V1__create_mission_table.sql
 * … V18__drop_mission_restored_audit_action.sql
 */

